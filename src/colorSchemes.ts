export type ColorSchemeId = (typeof COLOR_SCHEMES)[number]["id"];

export function getColorScheme(id: string | null | undefined): ColorScheme {
  return COLOR_SCHEMES.find((scheme) => scheme.id === id) || COLOR_SCHEMES.find((scheme) => scheme.id === DEFAULT_COLOR_SCHEME_ID) || COLOR_SCHEMES[0];
}

export function isColorSchemeId(id: string | null | undefined): id is ColorSchemeId {
  return COLOR_SCHEMES.some((scheme) => scheme.id === id);
}

export function applyColorScheme(id: string | null | undefined) {
  const theme = getColorScheme(id);
  const root = document.documentElement;
  root.dataset.colorScheme = theme.id;

  for (const [key, value] of Object.entries(theme.ui)) {
    const cssName = key.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
    root.style.setProperty(`--app-${cssName}`, value);
  }

  root.style.setProperty("--form-surface", theme.ui.input);
  root.style.setProperty("--form-surface-hover", theme.ui.surfaceHover);
  root.style.setProperty("--form-surface-border", theme.ui.borderMuted);
  root.style.setProperty("--form-surface-border-focus", theme.ui.accent);
  root.style.setProperty("--form-text", theme.ui.text);
  root.style.setProperty("--form-muted", theme.ui.muted);
  root.style.setProperty("--form-accent", theme.ui.accent);
  root.style.setProperty("--form-danger", theme.ui.danger);
  root.style.setProperty("--form-success", theme.ui.success);
  root.style.setProperty("--terminal-background", theme.xterm.background || theme.ui.background);
}
