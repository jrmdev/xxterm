import type { ITheme } from "@xterm/xterm";

type UiTheme = {
  background: string;
  surface: string;
  surfaceAlt: string;
  surfaceHover: string;
  border: string;
  borderMuted: string;
  text: string;
  muted: string;
  subtle: string;
  empty: string;
  accent: string;
  accentHover: string;
  danger: string;
  success: string;
  warning: string;
  selection: string;
  overlay: string;
  input: string;
  inputBorder: string;
  progressTrack: string;
  scrollbar: string;
};

export type ColorScheme = {
  id: string;
  label: string;
  xterm: ITheme;
  ui: UiTheme;
};

export const DEFAULT_COLOR_SCHEME_ID = "one-dark";

function scheme<T extends string>(id: T, label: string, xterm: ITheme, ui?: Partial<UiTheme>): ColorScheme & { id: T } {
  const background = xterm.background || "#1e1e1e";
  const foreground = xterm.foreground || "#cccccc";
  const accent = xterm.blue || "#4ea1ff";
  const danger = xterm.red || "#e06c75";
  const success = xterm.green || "#72d5a4";
  const warning = xterm.yellow || "#dcdcaa";

  return {
    id,
    label,
    xterm: {
      scrollbarSliderBackground: "rgba(255, 255, 255, 0.24)",
      scrollbarSliderHoverBackground: "rgba(255, 255, 255, 0.36)",
      ...xterm,
    },
    ui: {
      background,
      surface: background,
      surfaceAlt: ui?.surfaceAlt || xterm.black || "#2d2d2d",
      surfaceHover: ui?.surfaceHover || xterm.brightBlack || "#3a3a3a",
      border: ui?.border || xterm.brightBlack || "#444444",
      borderMuted: ui?.borderMuted || "rgba(255, 255, 255, 0.1)",
      text: foreground,
      muted: ui?.muted || xterm.white || "#999999",
      subtle: ui?.subtle || xterm.brightBlack || "#666666",
      empty: ui?.empty || xterm.black || "#555555",
      accent,
      accentHover: ui?.accentHover || xterm.brightBlue || accent,
      danger,
      success,
      warning,
      selection: ui?.selection || xterm.selectionBackground || xterm.brightBlack || "#31343a",
      overlay: ui?.overlay || "rgba(0, 0, 0, 0.56)",
      input: ui?.input || xterm.black || "#2b2b2b",
      inputBorder: ui?.inputBorder || xterm.brightBlack || "#404040",
      progressTrack: ui?.progressTrack || xterm.black || "#2c2c2c",
      scrollbar: ui?.scrollbar || xterm.brightBlack || "#5c5c5c",
      ...ui,
    },
  };
}

